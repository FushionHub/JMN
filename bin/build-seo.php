<?php
declare(strict_types=1);

/**
 * SEO build / verification tool
 * Jamachi Maurice Mauricennadi Portfolio Platform
 *
 * CLI only (web access to /bin is denied in .htaccess).
 *
 *   php bin/build-seo.php              regenerate sitemap.xml, then verify
 *   php bin/build-seo.php --check      verify only, write nothing
 *
 * What it does:
 *   1  Regenerates sitemap.xml from the static page list plus every project
 *      and article slug in data/ (DB first, hardcoded fallback second).
 *   2  Verifies that every jmn.morexweb.com URL mentioned in robots.txt,
 *      llm.txt and llms.md exists in the sitemap, and that every sitemap URL
 *      actually resolves to a real PHP file.
 *   3  Verifies the IndexNow key file and the robots.txt Sitemap directive.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit("This tool is CLI only.\n");
}

require_once dirname(__DIR__) . '/config/config.php';
require_once dirname(__DIR__) . '/data/projects.php';
require_once dirname(__DIR__) . '/data/articles.php';

$checkOnly = in_array('--check', $argv ?? [], true);
$root      = ROOT_PATH;
$origin    = rtrim(BASE_URL, '/');

// ---------------------------------------------------------------------------
// URL model
// ---------------------------------------------------------------------------

/** @var list<array{loc: string, priority: float}> $pages */
$pages = [
    ['loc' => $origin . '/index.php',             'priority' => 1.0],
    ['loc' => $origin . '/about.php',             'priority' => 0.9],
    ['loc' => $origin . '/projects.php',          'priority' => 0.9],
    ['loc' => $origin . '/services.php',          'priority' => 0.9],
    ['loc' => $origin . '/resume.php',            'priority' => 0.8],
    ['loc' => $origin . '/contact.php',           'priority' => 0.8],
    ['loc' => $origin . '/blog.php',              'priority' => 0.7],
    ['loc' => $origin . '/cookie-policy.php',     'priority' => 0.3],
    ['loc' => $origin . '/privacy-policy.php',    'priority' => 0.3],
    ['loc' => $origin . '/terms.php',             'priority' => 0.3],
];

try {
    foreach (get_all_projects() as $p) {
        $slug = (string) ($p['slug'] ?? '');
        if ($slug !== '') {
            $pages[] = [
                'loc'      => $origin . '/single-project.php?slug=' . rawurlencode($slug),
                'priority' => 0.8,
            ];
        }
    }
} catch (Throwable $e) {
    fwrite(STDERR, 'WARN: projects unavailable (' . $e->getMessage() . ")\n");
}

try {
    foreach (get_all_articles() as $a) {
        $slug = (string) ($a['slug'] ?? '');
        if ($slug !== '') {
            $pages[] = [
                'loc'      => $origin . '/blog-detail.php?slug=' . rawurlencode($slug),
                'priority' => 0.6,
            ];
        }
    }
} catch (Throwable $e) {
    fwrite(STDERR, 'WARN: articles unavailable (' . $e->getMessage() . ")\n");
}

$locs = array_values(array_unique(array_column($pages, 'loc')));

// ---------------------------------------------------------------------------
// 1. Write sitemap.xml
// ---------------------------------------------------------------------------

$today = date('Y-m-d');

function jmn_priority(float $p): string
{
    return rtrim(rtrim(number_format($p, 1, '.', ''), '0'), '.');
}

if (!$checkOnly) {
    $priorityFor = [];
    foreach ($pages as $p) {
        $priorityFor[$p['loc']] = $p['priority'];
    }

    $xml  = '<?xml version="1.0" encoding="UTF-8"?>' . "\n";
    $xml .= "<!--\n";
    $xml .= "  sitemap.xml - JMN ({$origin})\n";
    $xml .= "  Auto-generated by bin/build-seo.php on {$today} - do not edit by hand.\n";
    $xml .= "  Every entry matches the <link rel=\"canonical\"> emitted by includes/header.php.\n";
    $xml .= "-->\n";
    $xml .= "<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n";

    foreach ($locs as $loc) {
        $pr = $priorityFor[$loc] ?? 0.5;
        $freq = 'monthly';
        if ($pr >= 1.0 || str_ends_with($loc, '/index.php')) {
            $freq = 'weekly';
        } elseif (str_contains($loc, 'single-project.php') || str_contains($loc, 'blog-detail.php')) {
            $freq = str_contains($loc, 'blog-detail.php') ? 'yearly' : 'monthly';
        } elseif ($pr <= 0.3) {
            $freq = 'yearly';
        }

        $xml .= "  <url>\n";
        $xml .= '    <loc>' . htmlspecialchars($loc, ENT_XML1 | ENT_QUOTES, 'UTF-8') . "</loc>\n";
        $xml .= "    <lastmod>{$today}</lastmod>\n";
        $xml .= "    <changefreq>{$freq}</changefreq>\n";
        $xml .= '    <priority>' . jmn_priority($pr) . "</priority>\n";
        $xml .= "  </url>\n";
    }

    $xml .= "</urlset>\n";

    if (@file_put_contents($root . '/sitemap.xml', $xml) === false) {
        fwrite(STDERR, "ERROR: could not write sitemap.xml\n");
        exit(1);
    }
    echo 'wrote sitemap.xml  (' . count($locs) . " urls)\n";
}

// ---------------------------------------------------------------------------
// 2. Verification
// ---------------------------------------------------------------------------

/** @return list<string> */
function jmn_file_urls(string $path, string $origin): array
{
    if (!is_file($path)) {
        return [];
    }
    $text = (string) @file_get_contents($path);
    preg_match_all('#https?://[^\s\)\]>"\'`,]+#', $text, $m);
    $out = [];
    foreach ($m[0] as $u) {
        $u = rtrim($u, '.,');
        if (stripos($u, $origin . '/') === 0 || $u === $origin) {
            $out[] = preg_replace('/#.*$/', '', $u) ?? $u;
        }
    }
    return array_values(array_unique($out));
}

$errors = [];
$notes  = [];

// sitemap must be parseable and point at real files
$sitemapText = (string) @file_get_contents($root . '/sitemap.xml');
if (preg_match_all('#<loc>\s*([^<\s]+)\s*</loc>#i', $sitemapText, $m)) {
    foreach ($m[1] as $loc) {
        $path = parse_url($loc, PHP_URL_PATH) ?? '';
        $file = ltrim($path, '/');
        if ($file === '' || $file === '/') {
            $file = 'index.php';
        }
        if (!is_file($root . '/' . $file)) {
            $errors[] = "sitemap -> missing file {$file}";
        }
    }
} else {
    $errors[] = 'sitemap.xml contains no <loc> entries';
}

$sitemapUrls = [];
if (preg_match_all('#<loc>\s*([^<\s]+)\s*</loc>#i', $sitemapText, $m)) {
    $sitemapUrls = array_map('trim', $m[1]);
}

// llm.txt / llms.md references must be in the sitemap (page links only:
// assets, key files and endpoints are not indexable entries)
$nonPagePrefixes = ['/config/', '/includes/', '/data/', '/storage/', '/bin/', '/assets/'];
$nonPageExact    = ['/indexnow.php'];

foreach (['llm.txt', 'llms.md'] as $seoFile) {
    $refs = jmn_file_urls($root . '/' . $seoFile, $origin);
    if ($refs === []) {
        $errors[] = "{$seoFile}: no internal links found";
        continue;
    }
    $checked = 0;
    foreach ($refs as $u) {
        $path = (string) (parse_url($u, PHP_URL_PATH) ?? '');
        if (!str_ends_with($path, '.php')) {
            continue;
        }
        $skip = false;
        foreach ($nonPagePrefixes as $prefix) {
            if (str_starts_with($path, $prefix)) {
                $skip = true;
                break;
            }
        }
        if ($skip || in_array($path, $nonPageExact, true)) {
            continue;
        }
        // Template placeholders in the docs, e.g. ...?slug={slug}, are not URLs.
        if (str_contains($u, '{') || str_contains($u, '}')) {
            continue;
        }
        $checked++;
        if (!in_array($u, $sitemapUrls, true)) {
            $errors[] = "{$seoFile} -> not in sitemap: {$u}";
        }
    }
    if ($checked === 0) {
        $errors[] = "{$seoFile}: no page links found";
    }
    $notes[] = sprintf('%s: %d page link(s) cross-checked against the sitemap', $seoFile, $checked);
}

// robots.txt
$robots = (string) @file_get_contents($root . '/robots.txt');
if ($robots === '') {
    $errors[] = 'robots.txt missing';
} else {
    if (stripos($robots, 'Sitemap: ' . $origin . '/sitemap.xml') === false) {
        $errors[] = 'robots.txt has no Sitemap directive for ' . $origin . '/sitemap.xml';
    }
    if (preg_match('/^Disallow:\s*\/config\/\s*$/mi', $robots) !== 1) {
        $errors[] = 'robots.txt does not disallow /config/';
    }
    if (stripos($robots, 'User-agent: GPTBot') === false) {
        $notes[] = 'robots.txt: no explicit GPTBot block (covered by User-agent: *)';
    }
}

// IndexNow key file
$keyText = trim((string) @file_get_contents($root . '/' . INDEXNOW_KEY_FILE));
if ($keyText !== INDEXNOW_KEY) {
    $errors[] = INDEXNOW_KEY_FILE . ' missing or does not contain the key';
} else {
    $notes[] = INDEXNOW_KEY_FILE . ': ok';
}

// canonical tags vs sitemap: every page must declare $canonicalUrl = url(...)
// and the file part of that expression must match the sitemap path.
$canonicalMismatches = 0;
$canonicalChecked    = 0;

foreach ($locs as $loc) {
    $path = (string) (parse_url($loc, PHP_URL_PATH) ?? '');
    $file = ltrim($path, '/');
    if ($file === '' || !is_file($root . '/' . $file)) {
        continue;
    }

    $src = (string) @file_get_contents($root . '/' . $file);
    if (!preg_match('#\$canonicalUrl\s*=\s*url\((.*?)\);#s', $src, $cm)) {
        $errors[] = "{$file}: no \$canonicalUrl assignment (header.php falls back to SCRIPT_NAME)";
        continue;
    }

    // First quoted string in the expression is the file (before any ?slug=).
    if (!preg_match('#([a-z0-9_-]+\.php)#i', $cm[1], $fm)) {
        continue;
    }
    $canonicalChecked++;
    if (strcasecmp($fm[1], $file) !== 0) {
        $canonicalMismatches++;
        $errors[] = "{$file}: canonical points at {$fm[1]} but sitemap lists {$file}";
    }
}
$notes[] = sprintf('canonical check: %d/%d sitemap urls verified against page $canonicalUrl', $canonicalChecked, count($locs));


// ---------------------------------------------------------------------------
// Report
// ---------------------------------------------------------------------------

foreach ($notes as $n) {
    echo "  - {$n}\n";
}

if ($errors !== []) {
    echo "\nFAILED (" . count($errors) . "):\n";
    foreach ($errors as $e) {
        echo "  x {$e}\n";
    }
    exit(1);
}

echo "\nOK - all SEO checks passed (" . count($locs) . " urls).\n";
exit(0);
